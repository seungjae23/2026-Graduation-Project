String generateRandomWord([Random? random]) {
  final generator = random ?? Random();
  return signPlayWords[generator.nextInt(signPlayWords.length)];
}

List<String> generateRoundWords({
  int count = 5,
  String? seed,
}) {
  final random = seed == null || seed.isEmpty
      ? Random()
      : Random(_seedFromText(seed));
  final words = <String>[];

  while (words.length < count) {
    final word = generateRandomWord(random);

    if (!words.contains(word)) {
      words.add(word);
    }
  }

  return words;
}

String normalizeKslText(String value) {
  return displayKslText(value).replaceAll(RegExp(r'\s+'), '').toLowerCase();
}

String displayKslText(String value) {
  return _composeHangulJamo(value.trim());
}

String _composeHangulJamo(String value) {
  final buffer = StringBuffer();
  final codePoints = value.runes.toList();
  var index = 0;

  while (index < codePoints.length) {
    final leadingIndex = _leadingJamoIndex(codePoints[index]);

    if (leadingIndex == -1 || index + 1 >= codePoints.length) {
      buffer.writeCharCode(codePoints[index]);
      index += 1;
      continue;
    }

    final vowelIndex = _vowelJamoIndex(codePoints[index + 1]);

    if (vowelIndex == -1) {
      buffer.writeCharCode(codePoints[index]);
      index += 1;
      continue;
    }

    var trailingIndex = 0;
    var consumed = 2;

    if (index + 2 < codePoints.length) {
      final maybeTrailingIndex = _trailingJamoIndex(codePoints[index + 2]);
      final nextIsVowel = index + 3 < codePoints.length &&
          _vowelJamoIndex(codePoints[index + 3]) != -1;

      if (maybeTrailingIndex != -1 && !nextIsVowel) {
        trailingIndex = maybeTrailingIndex;
        consumed = 3;
      }
    }

    final syllableCode = 0xAC00 +
        ((leadingIndex * 21 + vowelIndex) * 28) +
        trailingIndex;
    buffer.writeCharCode(syllableCode);
    index += consumed;
  }

  return buffer.toString();
}

int _leadingJamoIndex(int codePoint) {
  const leadingJamo = <int>[
    0x1100,
    0x1101,
    0x1102,
    0x1103,
    0x1104,
    0x1105,
    0x1106,
    0x1107,
    0x1108,
    0x1109,
    0x110A,
    0x110B,
    0x110C,
    0x110D,
    0x110E,
    0x110F,
    0x1110,
    0x1111,
    0x1112,
  ];

  return leadingJamo.indexOf(codePoint);
}

int _vowelJamoIndex(int codePoint) {
  if (codePoint < 0x1161 || codePoint > 0x1175) {
    return -1;
  }

  return codePoint - 0x1161;
}

int _trailingJamoIndex(int codePoint) {
  if (codePoint < 0x11A8 || codePoint > 0x11C2) {
    return -1;
  }

  return codePoint - 0x11A7;
}

int _seedFromText(String text) {
  var hash = 0x811C9DC5;

  for (final codeUnit in text.codeUnits) {
    hash ^= codeUnit;
    hash = (hash * 0x01000193) & 0x7FFFFFFF;
  }

  return hash;
}
