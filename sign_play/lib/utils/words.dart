String generateRandomWord([Random? random]) {
  final generator = random ?? Random();
  return signPlayWords[generator.nextInt(signPlayWords.length)];
}

List<String> generateRoundWords({
  int count = 5,
  String? seed,
}) {
  final random = seed == null || seed.isEmpty
      ? Random()
      : Random(_seedFromText(seed));
  final words = <String>[];

  while (words.length < count) {
    final word = generateRandomWord(random);

    if (!words.contains(word)) {
      words.add(word);
    }
  }

  return words;
}

int _seedFromText(String text) {
  var hash = 0x811C9DC5;

  for (final codeUnit in text.codeUnits) {
    hash ^= codeUnit;
    hash = (hash * 0x01000193) & 0x7FFFFFFF;
  }

  return hash;
}
